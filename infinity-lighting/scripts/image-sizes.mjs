// Reads the pixel dimensions of every JPEG/PNG under public/ and writes src/data/imageSizes.js.
// Components spread imgSize(src) onto <img> so the browser reserves space before the image loads
// (no layout shift). Run after adding images: `node scripts/image-sizes.mjs`. Also runs on `npm run build`.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pub = path.join(root, 'public')
const out = path.join(root, 'src', 'data', 'imageSizes.js')

const pngSize = (buf) => (buf.readUInt32BE(12) === 0x49484452 ? [buf.readUInt32BE(16), buf.readUInt32BE(20)] : null)

const jpegSize = (buf) => {
  if (buf[0] !== 0xff || buf[1] !== 0xd8) return null
  let i = 2
  while (i < buf.length) {
    if (buf[i] !== 0xff) { i++; continue }
    const marker = buf[i + 1]
    if (marker === 0xd8 || (marker >= 0xd0 && marker <= 0xd7) || marker === 0x01) { i += 2; continue }
    const len = buf.readUInt16BE(i + 2)
    // SOF0..SOF15 except DHT (C4), JPG (C8), DAC (CC)
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return [buf.readUInt16BE(i + 7), buf.readUInt16BE(i + 5)]
    }
    i += 2 + len
  }
  return null
}

// EXIF orientation 5-8 means the stored image is rotated 90°, so displayed width/height swap.
const jpegOrientationSwaps = (buf) => {
  const app1 = buf.indexOf(Buffer.from([0xff, 0xe1]))
  if (app1 < 0 || buf.toString('ascii', app1 + 4, app1 + 10) !== 'Exif\0\0') return false
  const tiff = app1 + 10
  const le = buf.toString('ascii', tiff, tiff + 2) === 'II'
  const u16 = (o) => (le ? buf.readUInt16LE(o) : buf.readUInt16BE(o))
  const u32 = (o) => (le ? buf.readUInt32LE(o) : buf.readUInt32BE(o))
  const ifd = tiff + u32(tiff + 4)
  if (ifd + 2 > buf.length) return false
  const n = u16(ifd)
  for (let k = 0; k < n; k++) {
    const e = ifd + 2 + k * 12
    if (e + 12 > buf.length) break
    if (u16(e) === 0x0112) return u16(e + 8) >= 5
  }
  return false
}

const sizes = {}
const walk = (dir) => {
  for (const name of fs.readdirSync(dir)) {
    const fp = path.join(dir, name)
    if (fs.statSync(fp).isDirectory()) { walk(fp); continue }
    const ext = name.toLowerCase().split('.').pop()
    if (!['jpg', 'jpeg', 'png'].includes(ext)) continue
    const buf = fs.readFileSync(fp)
    let size = ext === 'png' ? pngSize(buf) : jpegSize(buf)
    if (!size) { console.warn(`could not read dimensions: ${fp}`); continue }
    if (ext !== 'png' && jpegOrientationSwaps(buf)) size = [size[1], size[0]]
    sizes['/' + path.relative(pub, fp).split(path.sep).join('/')] = size
  }
}
walk(pub)

const body = Object.keys(sizes).sort().map(k => `  ${JSON.stringify(k)}: [${sizes[k][0]}, ${sizes[k][1]}]`).join(',\n')
fs.writeFileSync(out, `// Generated by scripts/image-sizes.mjs. Do not edit by hand.
// Pixel dimensions of every image under public/, keyed by site path.
export const imageSizes = {
${body}
}

// Spread onto an <img>: <img src={src} {...imgSize(src)} />
export const imgSize = (src) => {
  const s = imageSizes[src]
  return s ? { width: s[0], height: s[1] } : {}
}
`)
console.log(`imageSizes.js written with ${Object.keys(sizes).length} images`)
